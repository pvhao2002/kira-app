import AsyncStorage from '@react-native-async-storage/async-storage';
import React, {createContext, useCallback, useContext, useEffect, useState} from 'react';

export type Lang = 'vi' | 'en';
const KEY = 'kira-life-lang';
type Vars = Record<string, string | number>;

function apply(template: string, vars?: Vars) {
  return vars ? template.replace(/\{\{(\w+)\}\}/g, (_, k) => String(vars[k] ?? '')) : template;
}

export function translate(template: string, lang: Lang, vars?: Vars) {
  const text = lang === 'en' ? dictionary[template] ?? template : template;
  return apply(text, vars);
}

type LanguageCtx = { lang: Lang; setLang: (l: Lang) => void; toggle: () => void };
const Context = createContext<LanguageCtx | null>(null);

export function LanguageProvider({children}: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>('vi');
  useEffect(() => {
    AsyncStorage.getItem(KEY).then(v => {
      if (v === 'en' || v === 'vi') setLangState(v);
    });
  }, []);

  function setLang(l: Lang) {
    setLangState(l);
    AsyncStorage.setItem(KEY, l).catch(() => {
    });
  }

  return <Context.Provider
    value={{lang, setLang, toggle: () => setLang(lang === 'vi' ? 'en' : 'vi')}}>{children}</Context.Provider>;
}

export function useLanguage() {
  const ctx = useContext(Context);
  if (!ctx) throw new Error('Missing LanguageProvider');
  return ctx;
}

export function useT() {
  const {lang} = useLanguage();
  return useCallback((template: string, vars?: Vars) => translate(template, lang, vars), [lang]);
}

