-- Kira News 247 initial schema (Oracle Autonomous Database / Oracle 23ai Free).

CREATE TABLE news_user (
    id            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR2(60 CHAR)  NOT NULL,
    display_name  VARCHAR2(120 CHAR) NOT NULL,
    password_hash VARCHAR2(100 CHAR) NOT NULL,
    role          VARCHAR2(20 CHAR)  NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_news_user_username UNIQUE (username),
    CONSTRAINT ck_news_user_role CHECK (role IN ('ADMIN', 'EDITOR'))
);

CREATE TABLE category (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        VARCHAR2(80 CHAR)  NOT NULL,
    name        VARCHAR2(120 CHAR) NOT NULL,
    description VARCHAR2(500 CHAR),
    sort_order  NUMBER(5) DEFAULT 0 NOT NULL,
    CONSTRAINT uq_category_slug UNIQUE (slug)
);

CREATE TABLE article (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug            VARCHAR2(200 CHAR)  NOT NULL,
    title           VARCHAR2(300 CHAR)  NOT NULL,
    summary         VARCHAR2(1000 CHAR),
    body_markdown   CLOB NOT NULL,
    body_html       CLOB NOT NULL,
    reading_minutes NUMBER(4) DEFAULT 1 NOT NULL,
    category_id     NUMBER(19) NOT NULL,
    tags            VARCHAR2(1000 CHAR),
    cover_image_url VARCHAR2(1000 CHAR),
    source_urls     VARCHAR2(4000 CHAR),
    status          VARCHAR2(30 CHAR) NOT NULL,
    revision        NUMBER(6) DEFAULT 1 NOT NULL,
    created_by      VARCHAR2(60 CHAR) NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at    TIMESTAMP WITH TIME ZONE,
    view_count      NUMBER(19) DEFAULT 0 NOT NULL,
    version         NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT uq_article_slug UNIQUE (slug),
    CONSTRAINT fk_article_category FOREIGN KEY (category_id) REFERENCES category (id),
    CONSTRAINT ck_article_status CHECK (status IN
        ('DRAFT', 'IN_REVIEW', 'CHANGES_REQUESTED', 'PUBLISHED', 'REJECTED', 'ARCHIVED'))
);
CREATE INDEX ix_article_status_published ON article (status, published_at);
CREATE INDEX ix_article_category ON article (category_id, status, published_at);

CREATE TABLE article_revision (
    id            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id    NUMBER(19) NOT NULL,
    revision      NUMBER(6)  NOT NULL,
    title         VARCHAR2(300 CHAR) NOT NULL,
    summary       VARCHAR2(1000 CHAR),
    body_markdown CLOB NOT NULL,
    edited_by     VARCHAR2(60 CHAR) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_article_revision UNIQUE (article_id, revision),
    CONSTRAINT fk_revision_article FOREIGN KEY (article_id) REFERENCES article (id)
);

CREATE TABLE review_comment (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id      NUMBER(19) NOT NULL,
    author          VARCHAR2(60 CHAR) NOT NULL,
    author_role     VARCHAR2(20 CHAR) NOT NULL,
    body            CLOB NOT NULL,
    quote           VARCHAR2(1000 CHAR),
    revision        NUMBER(6) NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at     TIMESTAMP WITH TIME ZONE,
    resolved_by     VARCHAR2(60 CHAR),
    resolution_note VARCHAR2(2000 CHAR),
    CONSTRAINT fk_comment_article FOREIGN KEY (article_id) REFERENCES article (id)
);
CREATE INDEX ix_comment_article ON review_comment (article_id, resolved_at);

CREATE TABLE read_event (
    id            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id    NUMBER(19) NOT NULL,
    read_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    visitor_id    VARCHAR2(64 CHAR),
    session_id    VARCHAR2(64 CHAR),
    ip            VARCHAR2(64 CHAR),
    hostname      VARCHAR2(255 CHAR),
    city          VARCHAR2(120 CHAR),
    region        VARCHAR2(120 CHAR),
    country       VARCHAR2(8 CHAR),
    loc           VARCHAR2(40 CHAR),
    org           VARCHAR2(255 CHAR),
    postal        VARCHAR2(20 CHAR),
    timezone      VARCHAR2(64 CHAR),
    remote_ip     VARCHAR2(64 CHAR),
    user_agent    VARCHAR2(500 CHAR),
    referrer      VARCHAR2(1000 CHAR),
    language      VARCHAR2(40 CHAR),
    screen_width  NUMBER(6),
    screen_height NUMBER(6),
    CONSTRAINT fk_read_article FOREIGN KEY (article_id) REFERENCES article (id)
);
CREATE INDEX ix_read_event_time ON read_event (read_at);
CREATE INDEX ix_read_event_article ON read_event (article_id, visitor_id, read_at);

